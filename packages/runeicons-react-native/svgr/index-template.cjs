/**
 * Barrel template.
 *
 * Re-exports every generated icon under a PascalCase name derived from its
 * file, and emits the `IconName` union used by the runtime `<RuneIcon />`
 * lookup and by consumers typing icon names.
 */
const path = require('path');

const pascalCase = (slug) =>
  slug.split('-').filter(Boolean).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');

module.exports = function indexTemplate(files) {
  const slugs = files
    .map((file) => path.basename(file.path, path.extname(file.path)))
    .sort((a, b) => a.localeCompare(b));

  const exports = slugs
    .map((slug) => `export { default as ${pascalCase(slug)} } from './${slug}';`)
    .join('\n');

  const union = slugs.map((slug) => `  | '${slug}'`).join('\n');

  return `// AUTO-GENERATED by @svgr/cli — do not edit by hand.

${exports}

/** Every icon slug in the set. */
export type IconName =
${union};
`;
};
